#!/usr/bin/env python3
import os
import argparse
import json
import joblib
import numpy as np

HEADER_TEMPLATE = """/*
  Support Vector Machine Model for Arduino

  Memory-optimized Linear SVM implementation
  Generated by export_linear_svc_to_header.py
*/

#ifndef SVM_MODEL_H
#define SVM_MODEL_H

// Model metadata
const int NUM_FEATURES = {num_features};
const int NUM_CLASSES = {num_classes};

// Class names
const char* class_names[] = {{
{class_names}
}};

// Linear SVM weights (w) and bias (b) for each binary classifier
float weights[NUM_CLASSES][NUM_FEATURES] = {{
{weights}
}};

// Bias terms for each binary classifier
float bias[NUM_CLASSES] = {{
{bias}
}};

// Calculate dot product between feature vector and weight vector
float dotProduct(float* a, float* b) {{
  float result = 0.0f;
  for (int i = 0; i < NUM_FEATURES; i++) result += a[i] * b[i];
  return result;
}}

// Evaluate SVM decision function for a specific class (binary classifier)
float evaluateSVMForClass(float features[], int class_idx) {{
  float dot_product = dotProduct(features, weights[class_idx]);
  return dot_product + bias[class_idx];  // f(x) = w^T * x + b
}}

// Evaluate multi-class SVM using one-vs-all approach
String evaluateSVM(float features[]) {{
  float scores[NUM_CLASSES];
  int predicted_class = 0;
  float max_score = -1e9f;
  for (int i = 0; i < NUM_CLASSES; i++) {{
    scores[i] = evaluateSVMForClass(features, i);
    if (scores[i] > max_score) {{ max_score = scores[i]; predicted_class = i; }}
  }}
  return String(class_names[predicted_class]);
}}

// Compute raw decision scores for each class (one-vs-all)
void computeSVMDecisionScores(float features[], float out_scores[]) {{
  for (int i = 0; i < NUM_CLASSES; i++) out_scores[i] = evaluateSVMForClass(features, i);
}}

#endif
"""

def fmt_float_list(vals, per_line=8, precision=6):
    lines = []
    row = []
    for i, v in enumerate(vals):
        row.append(f"{v:.{precision}f}")
        if (i + 1) % per_line == 0:
            lines.append(", ".join(row))
            row = []
    if row:
        lines.append(", ".join(row))
    return ",\n    ".join(lines)

def fmt_weights_matrix(W, precision=6):
    rows = []
    for c in range(W.shape[0]):
        row = ", ".join(f"{v:.{precision}f}" for v in W[c])
        rows.append(f"  {{{row}}}")
    return ",\n".join(rows)

def export(model_path, out_path):
    blob = joblib.load(model_path)
    pipe = None
    le = None
    feat_cols = None
    clf = None
    scaler = None
    if isinstance(blob, dict):
        pipe = blob.get('pipeline')
        le = blob.get('label_encoder')
        feat_cols = blob.get('feature_cols')
        # Support bare estimator + scaler saved in dict
        if pipe is None and 'model' in blob:
            clf = blob.get('model')
            scaler = blob.get('scaler')
    else:
        # blob could be a Pipeline or a bare LinearSVC
        if hasattr(blob, 'named_steps'):
            pipe = blob

    if pipe is not None:
        clf = pipe.named_steps.get('clf')
        scaler = pipe.named_steps.get('scaler')

    # Fallback to bare estimator
    if clf is None and hasattr(blob, 'coef_') and hasattr(blob, 'intercept_'):
        clf = blob
        scaler = None

    if clf is None:
        raise RuntimeError("Could not locate LinearSVC in model. Expected a Pipeline with 'clf' or a bare LinearSVC.")

    coef = clf.coef_.astype(np.float32)    # shape: [num_classes, num_features]
    intercept = clf.intercept_.astype(np.float32)  # shape: [num_classes]

    if scaler is not None:
        mean = scaler.mean_.astype(np.float32)
        scale = scaler.scale_.astype(np.float32)
        if coef.shape[1] != mean.shape[0]:
            raise RuntimeError(f"Feature count mismatch: coef={coef.shape[1]} vs scaler.mean={mean.shape[0]}")
        w_adj = coef / scale
        b_adj = intercept - (coef * (mean / scale)).sum(axis=1)
    else:
        w_adj = coef
        b_adj = intercept

    # Handle Binary Case (LinearSVC returns 1 row for 2 classes)
    # C++ code expects NUM_CLASSES rows (One-vs-Rest)
    if w_adj.shape[0] == 1:
        print("Detected Binary Classifier. Expanding weights for One-vs-Rest compatibility...")
        # Class 0 (Negative): -w, -b
        # Class 1 (Positive):  w,  b
        w_adj = np.vstack([-w_adj, w_adj])
        b_adj = np.concatenate([-b_adj, b_adj])

    # Try to get class names
    if le is not None:
        classes = list(le.classes_)
    else:
        meta_path = os.path.splitext(model_path)[0] + '_meta.json'
        if os.path.exists(meta_path):
            try:
                with open(meta_path, 'r') as f:
                    meta = json.load(f)
                classes = meta.get('classes', [str(i) for i in range(coef.shape[0])])
                feat_cols = meta.get('feature_cols', feat_cols)
            except Exception:
                classes = [str(i) for i in range(coef.shape[0])]
        else:
            classes = [str(i) for i in range(coef.shape[0])]
    num_classes = len(classes)
    num_features = coef.shape[1]

    class_names = ",\n".join(f'  "{name}"' for name in classes)
    weights_str = fmt_weights_matrix(w_adj)
    bias_str = ", ".join(f"{b:.6f}" for b in b_adj)

    header = HEADER_TEMPLATE.format(
        num_features=num_features,
        num_classes=num_classes,
        class_names=class_names,
        weights=weights_str,
        bias=bias_str,
    )

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w") as f:
        f.write(header)

    print(f"Exported LinearSVC to {out_path}")
    print(f"Classes: {classes}")
    print(f"Shapes: weights={w_adj.shape}, bias={b_adj.shape}")
    if feat_cols is not None:
        print(f"Feature cols ({len(feat_cols)}): {feat_cols[:5]} ...")

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model-path", default="models/LinearSVC.pkl", help="Path to joblib model (.pkl)")
    ap.add_argument("--out-path", default="sketches/shared/svm_model.h", help="Output header path")
    args = ap.parse_args()
    export(args.model_path, args.out_path)

if __name__ == "__main__":
    main()